"""Build every report table and figure from finished runs (cheap: reads CSVs, no simulation).

  ./vpy tools/make_results.py      ->  docs/results.md, docs/figs/v2/*.png
"""
import glob
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from pomdp_pick.eval import figures, stats  # noqa: E402

FIGS = ROOT / "docs" / "figs" / "v2"


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--tag", default="v2", help="names docs/results_<tag>.md and docs/figs/<tag>/")
    a = ap.parse_args()
    global FIGS
    FIGS = ROOT / "docs" / "figs" / a.tag
    runs = ROOT / a.runs
    FIGS.mkdir(parents=True, exist_ok=True)
    parts = ["# v2 results (generated by `tools/make_results.py`)\n"]
    lc = figures.learning_curves(runs, FIGS / "learning_curves.png")
    parts += ["## Training curves\n", f"![learning curves](figs/{a.tag}/learning_curves.png)\n",
              lc.to_markdown(index=False, floatfmt=".3f") + "\n"]
    rl = sorted(set(glob.glob(str(runs / "eval/*_n200.csv"))) - set(glob.glob(str(runs / "eval/*pomcp*"))))
    if rl:
        df = pd.concat([pd.read_csv(p) for p in rl])
        figures.success_vs_sigma(df, FIGS / "success_vs_sigma.png")
        parts += ["## Success vs camera noise (200 episodes per σ per seed, shared seeds)\n",
                  f"![success vs sigma](figs/{a.tag}/success_vs_sigma.png)\n", stats.markdown_tables(df)]
        ce = df.groupby(["method", "sigma_mm"]).commit_err_mm.mean().unstack().round(1)
        parts += ["\n### Mean commit error (mm)\n", ce.to_markdown() + "\n"]
    pc = sorted(glob.glob(str(runs / "eval/*pomcp*_seed0_n*.csv")))
    if pc:
        dp = pd.concat([pd.read_csv(p) for p in pc])
        ref = None
        if rl:
            b = df[(df.method == "belief") & (df.sigma_mm == 10) & (df.episode < dp.episode.nunique())]
            ref = ("belief PPO (same episodes)", float(b.success.mean())) if len(b) else None
        figures.success_vs_budget(dp, FIGS / "success_vs_budget.png", reference=ref)
        parts += ["## POMCP: budget vs success vs CPU time (σ = 10 mm)\n",
                  f"![budget](figs/{a.tag}/success_vs_budget.png)\n",
                  figures.budget_table(dp).to_markdown(index=False, floatfmt=".3f") + "\n"]
    wm = runs / "world_model/report.json"
    if wm.exists():
        import json
        r = json.loads(wm.read_text())
        names = ["Px", "Py", "Pz", "sin2yaw", "cos2yaw", "μx", "μy", "sin2θ", "cos2θ", "σx", "σy", "σθ", "σ_ep"]
        parts += ["## World model (held-out episodes)\n",
                  f"grasp AUC = {r['grasp_auc']:.3f} on {r['n_val_commits']} held-out commits; "
                  f"split = {r.get('split', 'transition')}\n",
                  pd.DataFrame({"dim": names, "R²": r["val_r2_per_dim"], "MSE": r["val_mse_per_dim"]})
                  .to_markdown(index=False, floatfmt=".4f") + "\n"]
    (ROOT / "docs" / ("results.md" if a.tag == "v2" else f"results_{a.tag}.md")).write_text("\n".join(parts))
    print("wrote results for", a.tag)


if __name__ == "__main__":
    main()
